"""Generate the menuconfig screen geometry from one editable product table.

Run with Python 3; --check verifies that the committed Kconfig is current.
Hardware timings/drivers remain in their existing board configuration files.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "bsp/artinchip/drv/display/screen_profiles.json"
OUTPUT = ROOT / "bsp/artinchip/drv/display/Kconfig.profiles"


def render(profiles):
    lines = ["# Generated by tools/scripts/screen_profiles.py. Do not edit.", ""]
    seen = set()
    for p in profiles:
        symbol = p["symbol"]
        if symbol in seen:
            raise ValueError("Duplicate screen: " + symbol)
        seen.add(symbol)
        if len(p["model"]) != 2 or not p["model"].isdigit():
            raise ValueError("Model must contain exactly two decimal digits")
        for field in ("width", "height", "touch_width", "touch_height"):
            if not 1 < p[field] <= 9999:
                raise ValueError("Invalid " + field + " for " + symbol)
        if p["touch_to_native_cw"] not in (0, 90, 180, 270):
            raise ValueError("Invalid calibration rotation")
        lines += ["if " + symbol, ""]
        fields = {
            "MODEL": ("string", '"' + p["model"] + '"'),
            "BASE_WIDTH": ("int", p["width"]),
            "BASE_HEIGHT": ("int", p["height"]),
            "BASE_WIDTH_TEXT": ("string", '"%04d"' % p["width"]),
            "BASE_HEIGHT_TEXT": ("string", '"%04d"' % p["height"]),
            "TOUCH_WIDTH": ("int", p["touch_width"]),
            "TOUCH_HEIGHT": ("int", p["touch_height"]),
            "TOUCH_TO_NATIVE_CW": ("int", p["touch_to_native_cw"]),
            "TOUCH_FLIP_X": ("bool", "y" if p.get("touch_flip_x") else "n"),
            "TOUCH_FLIP_Y": ("bool", "y" if p.get("touch_flip_y") else "n"),
            "PROFILE_PRESENT": ("bool", "y"),
        }
        for name, (kind, value) in fields.items():
            lines += ["config AIC_SCREEN_" + name, "    " + kind,
                      "    default " + str(value), ""]
        lines += ["endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(json.loads(TABLE.read_text(encoding="utf-8")))
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("Screen profiles are stale; run tools/scripts/screen_profiles.py")
        print("Screen profiles: current")
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
        OUTPUT.write_text(result, encoding="utf-8")


if __name__ == "__main__":
    main()
