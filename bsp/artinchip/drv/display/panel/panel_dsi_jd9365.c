/*
 * Multi-screen JD9365 DSI panel driver.
 *
 * Screen / board are selected in menuconfig (Display Parameter menu):
 *   AIC_SCREEN_<folder-name>  selects the screen (one and only one)
 *   AIC_JD9365_*              derived timing / DSI / GPIO parameters
 *
 * GPIO family by screen:
 *   ST7703 style  RESET/ON/IOVCC        : most MIPI screens
 *   VMAXC59       RESET/ON/DeMux_EN    : no IOVCC, DeMux enable
 *   VMAXC30       AVDD/VDDIO/DVDD/ON/FD/RESET : separate power rails
 *   EDP (A54/C49) VCC/RESET + PWM3 backlight : DSI-to-eDP bridge
 */

static struct gpio_desc reset_gpio;
static struct gpio_desc on_gpio;
static struct gpio_desc iovcc_gpio;
static struct gpio_desc avdd_gpio;
static struct gpio_desc fd_gpio;
static struct gpio_desc demux_gpio;
static struct gpio_desc vddio_on_gpio;
static struct gpio_desc dvdd_on_gpio;

static void panel_gpio_init(struct aic_panel *panel)
{
#if defined(AIC_SCREEN_VMAXC40_12_6) || defined(AIC_SCREEN_VMAXC49_15_6) || defined(AIC_SCREEN_VMAXA67_11_6)
    /* HL6011 EDP: VCC=PE.9, RESET=PE.15; backlight is PWM3 on PE.18 */
    panel_get_gpio(&on_gpio, AIC_JD9365_ON_PIN);
    panel_get_gpio(&reset_gpio, AIC_JD9365_RESET_PIN);

    panel_gpio_set_value(&on_gpio, 0);
    aic_delay_ms(2);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(120);
    panel_gpio_set_value(&reset_gpio, 0);
    aic_delay_ms(20);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(120);
#elif defined(AIC_SCREEN_VMAXC30_6_67)
    /* VMAXC30: separate AVDD / VDDIO / DVDD / LCD_ON / FD / RESET rails */
    panel_get_gpio(&avdd_gpio, AIC_JD9365_AVDD_PIN);
    panel_get_gpio(&vddio_on_gpio, AIC_JD9365_VDDIO_ON_PIN);
    panel_get_gpio(&on_gpio, AIC_JD9365_ON_PIN);
    panel_get_gpio(&dvdd_on_gpio, AIC_JD9365_DVDD_ON_PIN);
    panel_get_gpio(&reset_gpio, AIC_JD9365_RESET_PIN);
    panel_get_gpio(&fd_gpio, AIC_JD9365_FD_PIN);

    panel_gpio_set_value(&vddio_on_gpio, 1);
    aic_delay_ms(2);
    panel_gpio_set_value(&dvdd_on_gpio, 1);
    aic_delay_ms(3);
    panel_gpio_set_value(&on_gpio, 0);
    aic_delay_ms(3);
    panel_gpio_set_value(&fd_gpio, 1);
    aic_delay_ms(5);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(120);
    panel_gpio_set_value(&reset_gpio, 0);
    aic_delay_ms(50);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(120);

    panel_gpio_set_value(&avdd_gpio, 1);
#elif defined(AIC_SCREEN_VMAXC59_14_5) || defined(AIC_SCREEN_VMAXC54_12_6)
    /* VMAXC59/VMAXC54: no IOVCC pin, has DeMux enable */
    panel_get_gpio(&reset_gpio, AIC_JD9365_RESET_PIN);
    panel_get_gpio(&demux_gpio, AIC_JD9365_DEMUX_EN_PIN);
    panel_get_gpio(&on_gpio, AIC_JD9365_ON_PIN);

    panel_gpio_set_value(&demux_gpio, 1);
    panel_gpio_set_value(&on_gpio, 0);
    aic_delay_ms(2);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(50);
    panel_gpio_set_value(&reset_gpio, 0);
    aic_delay_ms(50);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(150);
#else
    /* MIPI ST7703 style: RESET / ON / IOVCC */
    panel_get_gpio(&reset_gpio, AIC_JD9365_RESET_PIN);
    panel_get_gpio(&on_gpio, AIC_JD9365_ON_PIN);
    panel_get_gpio(&iovcc_gpio, AIC_JD9365_IOVCC_PIN);

    panel_gpio_set_value(&on_gpio, 0);
    panel_gpio_set_value(&iovcc_gpio, 0);
    aic_delay_ms(2);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(100);
    panel_gpio_set_value(&reset_gpio, 0);
    aic_delay_ms(50);
    panel_gpio_set_value(&reset_gpio, 1);
    aic_delay_ms(130);
#endif
}

